internal const val FAQ_TEXT = """1. 为什么「关注」要登录?
关注列表是账号私有数据,游客拿不到。选到关注档时会摆扫码入口,登录后自动补取。

2. 扫码登录安全吗?
二维码与轮询都只在本机与平台之间完成,没有中转;凭证存在本机账号盘,退出即清。

3. 为什么有些视频没有高清晰度?
清晰度由平台按身份与内容给,接口返回哪条就放哪条。本应用不绕过权限。

4. 每次进详情页都要重新选清晰度?
不用。「设置 → 播放 → 默认清晰度」钉一档,进片就按它起;这片没有那一档就退到不高于它的可用档。播放中仍可现改,改了不写回这一档。

5. 怎么让它少花我的流量?
「设置 → 播放 → 自动播放」选「仅 Wi-Fi」,移动网络下就停在第一帧等你按播放;「只在 Wi-Fi 下缓存」默认开着,移动网络上按下载会先问一句;不想切走还放声音,关掉「允许后台播放」。

6. 看片时屏幕自己睡了 / 切走了还在放声音?
「播放时屏幕常亮」与「允许后台播放」都在「设置 → 播放」里,两格默认都开。

7. 发评论/发弹幕失败怎么办?
按提示来:要求登录就去扫码;被风控或频率限制就歇一会儿,连点只会等更久。

8. 评论发出去了为什么没显示?
平台会审核,列表只在重新读第一页后更新。稍后再进来看看。

9. 历史里为什么少了一些看过的视频?
非视频路由、缺少 bvid 的条目会被剔掉并在底部报数;开了「看完即清」也会在退出播放时删除。

10. 清理缓存会删掉收藏和历史吗?
不会。清理只碰 cacheDir;历史、收藏、登录凭据在别处,各有各的清理入口。

11. 断网还能用吗?
能翻本机历史、收藏与搜索词;新内容、评论与推荐需要联网。

12. 平板上怎么用?
窗口够宽时底栏变成左侧栏,详情页分成「播放/互动」与「评论/推荐」两栏。首页卡片默认按宽度排成多列,想一条一条看可以在「设置 → 外观与首页 → 排布」里换成单列。

13. 设置被我调乱了怎么办?
每一个二级页最下面都有一行「恢复本组默认」,只退那一组,别处不动。

14. 崩溃了怎么办?
关于 → 上次崩溃记录,可复制后自行决定是否公开。记录只在本机,没有自动上传。"""

