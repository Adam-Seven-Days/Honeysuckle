/**
 * 对话框:居中面板 + 一层压暗遮罩,按钮排右下。
 *
 * 与系统 Material 弹窗的差别只在观感:22dp 圆角、1dp 描边、无投影,标题/正文色分开给。
 * 行为口径不变 —— 点遮罩或返回键都走 [onDismissRequest]。
 */
@Composable
fun AlertDialog(
    onDismissRequest: () -> Unit,
    confirmButton: @Composable () -> Unit,
    modifier: Modifier = Modifier,
    dismissButton: (@Composable () -> Unit)? = null,
    title: (@Composable () -> Unit)? = null,
    text: (@Composable () -> Unit)? = null,
) {
    Dialog(
        onDismissRequest = onDismissRequest,
        properties = DialogProperties(usePlatformDefaultWidth = false),
    ) {
        Box(
            modifier = Modifier
                .fillMaxSize()
                .background(Color.Black.copy(alpha = 0.42f))
                .clickable(
                    interactionSource = remember { MutableInteractionSource() },
                    indication = null,
                    onClick = onDismissRequest,
                ),
            contentAlignment = Alignment.Center,
        ) {
            Surface(
                modifier = modifier
                    .padding(horizontal = 32.dp)
                    .clickable(
                        interactionSource = remember { MutableInteractionSource() },
                        indication = null,
                        onClick = {},
                    ),
                shape = RoundedCornerShape(Hsy.shapes.extraLarge),
                color = Hsy.colors.surface,
                border = BorderStroke(1.dp, Hsy.colors.outlineVariant),
            ) {
                Column(
                    modifier = Modifier.padding(24.dp),
                    verticalArrangement = Arrangement.spacedBy(12.dp),
                ) {
                    if (title != null) {
                        CompositionLocalProvider(LocalHsyContentColor provides Hsy.colors.onSurface) {
                            title()
                        }
                    }
                    if (text != null) {
                        CompositionLocalProvider(LocalHsyContentColor provides Hsy.colors.onSurfaceVariant) {
                            text()
                        }
                    }
                    Row(
                        modifier = Modifier.fillMaxWidth(),
                        horizontalArrangement = Arrangement.spacedBy(8.dp, Alignment.End),
                        verticalAlignment = Alignment.CenterVertically,
                    ) {
                        dismissButton?.invoke()
                        confirmButton()
                    }
                }
            }
        }
    }
}
